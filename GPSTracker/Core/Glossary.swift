    /// 要注意的限制
    let caveat: String?

    static func == (lhs: GlossaryTerm, rhs: GlossaryTerm) -> Bool { lhs.id == rhs.id }
    func hash(into hasher: inout Hasher) { hasher.combine(id) }
}

