/// App 裡所有專有名詞的白話解釋。
/// 每個數字旁邊的「?」都會開到這裡對應的條目。
struct GlossaryTerm: Identifiable, Hashable {
    let id: String
    /// 畫面上顯示的名稱
    let title: String
    /// 英文全稱（沒有就留空）
    let fullName: String
    /// 一句話說明這是什麼
    let summary: String
    /// 這個數字實際上在算什麼
